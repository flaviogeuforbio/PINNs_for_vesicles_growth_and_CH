def validate_grid_refinement(args: argparse.Namespace) -> Dict[str, float | bool]:
    """
    Perform a simple grid-refinement check at final time.

    Coarse, medium and fine grids are chosen so that the fine solution can be
    compared to coarser grids by direct sub-sampling.
    """
    n0 = args.n_x

    _, _, phi_coarse, *_ = run_once(
        n_x=n0,
        t_final=args.t_final,
        n_snap=args.n_snap,
        m_phi_true=args.m_phi_true,
        k=args.k,
        eps=args.eps,
        ic_a0=args.ic_a0,
        ic_b0=args.ic_b0,
        rtol=args.rtol,
        atol=args.atol,
    )

    _, _, phi_medium, *_ = run_once(
        n_x=2 * n0 - 1,
        t_final=args.t_final,
        n_snap=args.n_snap,
        m_phi_true=args.m_phi_true,
        k=args.k,
        eps=args.eps,
        ic_a0=args.ic_a0,
        ic_b0=args.ic_b0,
        rtol=args.rtol,
        atol=args.atol,
    )

    _, _, phi_fine, *_ = run_once(
        n_x=4 * n0 - 3,
        t_final=args.t_final,
        n_snap=args.n_snap,
        m_phi_true=args.m_phi_true,
        k=args.k,
        eps=args.eps,
        ic_a0=args.ic_a0,
        ic_b0=args.ic_b0,
        rtol=args.rtol,
        atol=args.atol,
    )

    err_coarse = l2_rel(phi_coarse[-1], phi_fine[-1][::4])
    err_medium = l2_rel(phi_medium[-1], phi_fine[-1][::2])

    ratio = err_coarse / err_medium if err_medium > 0.0 else np.inf
    passed = err_coarse < args.grid_tol

    return {
        "err_coarse_vs_fine": float(err_coarse),
        "err_medium_vs_fine": float(err_medium),
        "error_ratio": float(ratio),
        "tolerance": float(args.grid_tol),
        "passed": bool(passed),
    }


def validate_energy_decay(
    phi: np.ndarray,
    dx: float,
    weights: np.ndarray,
    args: argparse.Namespace,
) -> Tuple[np.ndarray, Dict[str, float | bool]]:
    """
    Compute the energy trajectory and check monotonicity.
    """
    energies = np.array(
        [
            energy(
                phi=phi[n],
                dx=dx,
                weights=weights,
                k=args.k,
                eps=args.eps,
            )
            for n in range(phi.shape[0])
        ]
    )

    d_energy = np.diff(energies)
    max_increase = float(d_energy.max())
    passed = max_increase <= args.energy_tol

    summary = {
        "energy_initial": float(energies[0]),
        "energy_final": float(energies[-1]),
        "max_energy_increment": max_increase,
        "tolerance": float(args.energy_tol),
        "passed": bool(passed),
    }

    return energies, summary


def validate_ls_recovery(
    phi: np.ndarray,
    t: np.ndarray,
    lap: np.ndarray,
    weights: np.ndarray,
    args: argparse.Namespace,
) -> Dict[str, float | bool]:
    """
    Check direct weak/strong least-squares recovery on clean solver data.

    This is an oracle validation check. It verifies that the clean full-grid
    trajectory contains enough information to recover the true mobility.
    """
    m_weak = weak_ls_estimate(
        phi_snaps=phi,
        t_snaps=t,
        lap=lap,
        weights=weights,
        k=args.k,
        eps=args.eps,
    )

    m_strong = strong_ls_estimate(
        phi_snaps=phi,
        t_snaps=t,
        lap=lap,
        weights=weights,
        k=args.k,
        eps=args.eps,
    )

    err_weak = abs(m_weak - args.m_phi_true) / abs(args.m_phi_true)
    err_strong = abs(m_strong - args.m_phi_true) / abs(args.m_phi_true)

    passed = (err_weak < args.ls_tol) and (err_strong < args.ls_tol)

    return {
        "m_phi_true": float(args.m_phi_true),
        "m_phi_weak_ls": float(m_weak),
        "m_phi_strong_ls": float(m_strong),
        "rel_error_weak": float(err_weak),
        "rel_error_strong": float(err_strong),
        "tolerance": float(args.ls_tol),
        "passed": bool(passed),
    }


