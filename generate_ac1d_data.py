def main() -> bool:
    """
    Generate the dataset, validate it, and save outputs.
    """
    args = parse_args()
    validate_args(args)

    out_npz = Path(args.out_npz)
    out_png = Path(args.out_png)
    out_json = Path(args.out_json)

    print("=" * 80)
    print("AC1D SOURCE-FREE DATA GENERATION")
    print("=" * 80)
    print(f"m_phi_true = {args.m_phi_true}")
    print(f"k          = {args.k}")
    print(f"eps        = {args.eps}")
    print(f"T_final    = {args.t_final}")
    print(f"N_x        = {args.n_x}")
    print(f"N_snap     = {args.n_snap}")
    print("=" * 80)

    # -------------------------------------------------------------------------
    # Main simulation
    # -------------------------------------------------------------------------
    x, t, phi, dx, lap, weights = run_once(
        n_x=args.n_x,
        t_final=args.t_final,
        n_snap=args.n_snap,
        m_phi_true=args.m_phi_true,
        k=args.k,
        eps=args.eps,
        ic_a0=args.ic_a0,
        ic_b0=args.ic_b0,
        rtol=args.rtol,
        atol=args.atol,
    )

    print("Main simulation completed.")
    print(f"phi shape : {phi.shape}")
    print(f"phi(t=0) : min={phi[0].min():+.6f} | max={phi[0].max():+.6f}")
    print(f"phi(t=T) : min={phi[-1].min():+.6f} | max={phi[-1].max():+.6f}")

    # -------------------------------------------------------------------------
    # Validation A: grid refinement
    # -------------------------------------------------------------------------
    print("-" * 80)
    print("(A) Grid refinement check")

    grid_summary = validate_grid_refinement(args)

    print(f"relative L2 error | coarse vs fine : {grid_summary['err_coarse_vs_fine']:.6e}")
    print(f"relative L2 error | medium vs fine : {grid_summary['err_medium_vs_fine']:.6e}")
    print(f"error ratio       | expected ~4    : {grid_summary['error_ratio']:.3f}")
    print(f"grid check passed                  : {grid_summary['passed']}")

    # -------------------------------------------------------------------------
    # Validation B: energy monotonicity
    # -------------------------------------------------------------------------
    print("-" * 80)
    print("(B) Energy monotonicity check")

    energies, energy_summary = validate_energy_decay(
        phi=phi,
        dx=dx,
        weights=weights,
        args=args,
    )

