"""
Generate source-free 1D Allen-Cahn data for blind inverse inference.

This script generates a clean numerical trajectory for the one-dimensional
Allen-Cahn equation:

    phi_t = -m_phi * mu

with chemical potential:

    mu = k * [ (1/eps) * (phi^3 - phi) - eps * phi_xx ]

and homogeneous Neumann boundary conditions:

    phi_x(0,t) = phi_x(1,t) = 0.

The data are generated by a classical method-of-lines discretization in space
and a stiff BDF solver in time. No manufactured source term is used. The true
mobility m_phi_true is used only to generate the trajectory and is saved for
final evaluation.

The generated dataset is intended for the source-free blind inverse benchmark,
where a PINN must infer m_phi from observations of phi(x,t).
"""

