def make_figure(
    x: np.ndarray,
    t: np.ndarray,
    phi: np.ndarray,
    energies: np.ndarray,
    out_png: Path,
) -> None:
    """
    Create a diagnostic figure with profiles, space-time map and energy decay.
    """
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.2))

    profile_indices = [
        0,
        len(t) // 4,
        len(t) // 2,
        3 * len(t) // 4,
        len(t) - 1,
    ]

    for idx in profile_indices:
        axes[0].plot(x, phi[idx], label=f"t={t[idx]:.2f}")

    axes[0].set_title(r"$\phi(x,t)$ profiles")
    axes[0].set_xlabel("x")
    axes[0].set_ylabel(r"$\phi$")
    axes[0].axhline(1.0, linestyle=":", linewidth=0.8)
    axes[0].axhline(-1.0, linestyle=":", linewidth=0.8)
    axes[0].legend(fontsize=8)

    image = axes[1].imshow(
        phi,
        aspect="auto",
        origin="lower",
        extent=[x[0], x[-1], t[0], t[-1]],
        vmin=-1.0,
        vmax=1.0,
    )

    axes[1].set_title(r"$\phi(x,t)$")
    axes[1].set_xlabel("x")
    axes[1].set_ylabel("t")

    fig.colorbar(image, ax=axes[1], fraction=0.046)

    axes[2].plot(t, energies, "-o", markersize=3)
    axes[2].set_title("Energy decay")
    axes[2].set_xlabel("t")
    axes[2].set_ylabel("E")

    fig.tight_layout()
    out_png.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_png, dpi=130)
    plt.close(fig)


def save_dataset(
    out_npz: Path,
    x: np.ndarray,
    t: np.ndarray,
    phi: np.ndarray,
    dx: float,
    energies: np.ndarray,
    args: argparse.Namespace,
) -> None:
    """
    Save the generated AC1D dataset to NPZ.
    """
    out_npz.parent.mkdir(parents=True, exist_ok=True)

    np.savez(
        out_npz,
        x=x,
        t=t,
        phi=phi,
        m_phi_true=args.m_phi_true,
        k=args.k,
        eps=args.eps,
        dx=dx,
        ic_a0=args.ic_a0,
        ic_b0=args.ic_b0,
        energy=energies,
    )


