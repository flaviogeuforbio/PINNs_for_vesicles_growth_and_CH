"""
Train a source-free 1D Allen-Cahn PINN for blind inverse inference of m_phi.

The network predicts only the physical phase field:

    (x, t) -> phi_theta(x, t)

The chemical potential is computed from phi_theta by automatic differentiation:

    mu_theta = k * [ (1/eps) * (phi_theta^3 - phi_theta)
                    - eps * phi_theta_xx ]

The inverse parameter is the mobility m_phi in:

    phi_t + m_phi * mu = 0

and is constrained to be positive through:

    m_phi = exp(log_m_phi)

The benchmark is source-free: no manufactured source term is used during
training. The true value m_phi_true appears only in the generated dataset and is
used here only for final diagnostics and reporting.
"""

