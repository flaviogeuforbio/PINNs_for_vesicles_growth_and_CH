def main() -> None:
    """
    Train the source-free AC1D inverse PINN and save final artifacts.
    """
    args = parse_args()
    validate_args(args)

    torch.manual_seed(args.seed)
    np.random.seed(args.seed)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    run_dir = Path(args.out_root) / args.run_name
    fig_dir = run_dir / "figures"
    weights_dir = run_dir / "weights"

    fig_dir.mkdir(parents=True, exist_ok=True)
    weights_dir.mkdir(parents=True, exist_ok=True)

    print("=" * 80)
    print("AC1D SOURCE-FREE BLIND INVERSE PINN")
    print("=" * 80)
    print(f"Device      : {device}")
    print(f"Data path   : {args.data_path}")
    print(f"Run dir     : {run_dir}")
    print(f"m_phi_init  : {args.m_phi_init}")
    print("=" * 80)

    data = load_ac1d_data(args=args, device=device)

    print("Loaded data:")
    print(f"  m_phi_true        = {data['m_phi_true']:.6f}")
    print(f"  k                 = {data['k']:.6f}")
    print(f"  eps               = {data['eps']:.6f}")
    print(f"  T_final           = {data['t_final']:.6f}")
    print(f"  total data points = {data['n_total']}")
    print(f"  observed points   = {data['n_obs']}")
    print(f"  data_fraction     = {args.data_fraction}")
    print(f"  data_noise        = {args.data_noise}")
    print("=" * 80)

    save_config(
        args=args,
        data=data,
        run_dir=run_dir,
    )

    model, log_m_phi, optimizer = initialize_model_and_optimizer(
        args=args,
        device=device,
    )

    generator = torch.Generator(device=device)
    generator.manual_seed(args.seed + 2000)

    history = init_history()

    run_pretraining(
        model=model,
        log_m_phi=log_m_phi,
        optimizer=optimizer,
        data=data,
        args=args,
        device=device,
        generator=generator,
        history=history,
    )

    run_adam_inverse_training(
        model=model,
        log_m_phi=log_m_phi,
        optimizer=optimizer,
        data=data,
        args=args,
        device=device,
        generator=generator,
        history=history,
    )

    run_lbfgs_refinement(
        model=model,
        log_m_phi=log_m_phi,
        data=data,
        args=args,
        device=device,
        generator=generator,
        history=history,
    )

    torch.save(model.state_dict(), weights_dir / "model.pt")

    final_m_phi = float(torch.exp(log_m_phi).detach().cpu())

    eval_results = evaluate_on_full_grid(
        model=model,
        data=data,
    )

    metrics = build_metrics(
        final_m_phi=final_m_phi,
        data=data,
        eval_results=eval_results,
        args=args,
    )

    save_metrics(metrics, run_dir / "metrics.json")
    save_history(history, run_dir / "history.json")

    plot_losses(history, fig_dir)
    plot_m_phi(history, data, fig_dir)
    plot_field_diagnostics(eval_results, data, fig_dir)

    print("\n" + "=" * 80)
    print("FINAL RESULTS")
    print("=" * 80)
    print(f"m_phi_true             : {metrics['m_phi_true']:.8e}")
    print(f"m_phi_final            : {metrics['m_phi_final']:.8e}")
    print(f"m_phi_relative_error   : {metrics['m_phi_relative_error']:.8e}")
    print(f"full_grid_mse_phi      : {metrics['full_grid_mse_phi']:.8e}")
    print(f"full_grid_rel_l2_phi   : {metrics['full_grid_relative_l2_phi']:.8e}")
    print(f"Saved run to           : {run_dir}")
    print("=" * 80)


if __name__ == "__main__":
    main()