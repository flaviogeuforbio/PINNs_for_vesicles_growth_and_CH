def true_initial_condition(x: Tensor, data: Dict[str, Any]) -> Tensor:
    """
    Exact initial condition used by generate_ac1d_data.py:

        phi(x,0) = ic_a0 + ic_b0*cos(pi*x).
    """
    if data["ic_a0"] is None or data["ic_b0"] is None:
        raise ValueError("ic_a0/ic_b0 not found in dataset.")

    return data["ic_a0"] + data["ic_b0"] * torch.cos(math.pi * x)


def evaluate_losses(
    model: nn.Module,
    log_m_phi: nn.Parameter,
    batch: Dict[str, Tensor],
    data: Dict[str, Any],
    args: argparse.Namespace,
    use_pde: bool,
) -> Tuple[Tensor, Dict[str, Tensor]]:
    """
    Evaluate the composite PINN loss on one fixed batch.

    Loss terms
    ----------
    1. Data loss:
       MSE between phi_theta and observed phi data.

    2. Initial-condition loss:
       MSE against the analytic initial condition.

    3. Boundary-condition loss:
       homogeneous Neumann condition phi_x(0,t)=phi_x(1,t)=0.

    4. PDE loss:
       source-free Allen-Cahn residual
           R = phi_t + m_phi * mu_theta.

    During pretraining, use_pde=False and the PDE term is set to zero.
    """
    m_phi = torch.exp(log_m_phi)

    # -------------------------------------------------------------------------
    # Supervised data loss
    # -------------------------------------------------------------------------
    phi_pred_data = model(batch["x_data"], batch["t_data"])
    loss_data = torch.mean((phi_pred_data - batch["phi_data"]) ** 2)

    # -------------------------------------------------------------------------
    # Initial-condition loss
    # -------------------------------------------------------------------------
    phi_pred_ic = model(batch["x_ic"], batch["t_ic"])
    phi_true_ic = true_initial_condition(batch["x_ic"], data)
    loss_ic = torch.mean((phi_pred_ic - phi_true_ic) ** 2)

    # -------------------------------------------------------------------------
    # Boundary loss: phi_x(0,t)=0 and phi_x(1,t)=0
    # -------------------------------------------------------------------------
    x_left = batch["x_bc_left"].detach().clone().requires_grad_(True)
    t_left = batch["t_bc_left"].detach().clone()

    x_right = batch["x_bc_right"].detach().clone().requires_grad_(True)
    t_right = batch["t_bc_right"].detach().clone()

    phi_left = model(x_left, t_left)
    phi_right = model(x_right, t_right)

    phi_x_left = grad(phi_left, x_left)
    phi_x_right = grad(phi_right, x_right)

    loss_bc = torch.mean(phi_x_left**2) + torch.mean(phi_x_right**2)

    # -------------------------------------------------------------------------
    # Source-free PDE residual loss
    # -------------------------------------------------------------------------
    if use_pde:
        x_pde = batch["x_pde"].detach().clone().requires_grad_(True)
        t_pde = batch["t_pde"].detach().clone().requires_grad_(True)

        phi_pde = model(x_pde, t_pde)
        phi_t = grad(phi_pde, t_pde)

        mu_pde = mu_from_phi(
            phi=phi_pde,
            x=x_pde,
            k=data["k"],
            eps=data["eps"],
        )

        residual = phi_t + m_phi * mu_pde
        loss_pde = torch.mean(residual**2)
    else:
        loss_pde = torch.zeros((), device=batch["x_data"].device)

    total = (
        args.data_weight * loss_data
        + args.ic_weight * loss_ic
        + args.bc_weight * loss_bc
        + args.pde_weight * loss_pde
    )

    losses = {
        "total": total,
        "data": loss_data,
        "ic": loss_ic,
        "bc": loss_bc,
        "pde": loss_pde,
        "m_phi": m_phi,
    }

    return total, losses


