    parser.add_argument("--lbfgs_iter", type=int, default=0)
    parser.add_argument("--print_every", type=int, default=100)

    # inverse parameter
    parser.add_argument("--m_phi_init", type=float, default=0.2)

    # sampling
    parser.add_argument("--n_data", type=int, default=10000)
