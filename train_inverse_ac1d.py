def save_config(args, data, run_dir):
    config = vars(args).copy()
    config.update(
        {
            "m_phi_true": data["m_phi_true"],
            "k": data["k"],
            "eps": data["eps"],
            "t_final": data["t_final"],
            "n_total_data_points": data["n_total"],
            "n_observed_data_points": data["n_obs"],
        }
    )

    with open(run_dir / "run_config.json", "w") as f:
        json.dump(config, f, indent=4)


def append_history(history, losses):
    for key in ["total", "data", "ic", "bc", "pde", "m_phi"]:
        history[key].append(float(losses[key].detach().cpu()))


def plot_losses(history, fig_dir):
    fig_dir.mkdir(parents=True, exist_ok=True)

    plt.figure(figsize=(8, 5))

    for key in ["total", "data", "pde", "ic", "bc"]:
        values = np.array(history[key], dtype=np.float64)
        values = np.maximum(values, 1e-16)
        plt.semilogy(values, label=key)

    plt.xlabel("Optimization step")
    plt.ylabel("Loss")
    plt.title("AC1D blind inverse training losses")
    plt.legend()
    plt.grid(True, which="both", linestyle="--", alpha=0.4)
    plt.tight_layout()
    plt.savefig(fig_dir / "losses.png", dpi=180)
    plt.close()


def plot_m_phi(history, data, fig_dir):
    plt.figure(figsize=(8, 5))

    m_vals = np.array(history["m_phi"], dtype=np.float64)
    plt.plot(m_vals, label=r"learned $m_\phi$")
    plt.axhline(data["m_phi_true"], linestyle="--", color="black", label=r"true $m_\phi$")

    plt.xlabel("Optimization step")
    plt.ylabel(r"$m_\phi$")
    plt.title("Blind inverse inference of mobility")
    plt.legend()
    plt.grid(True, alpha=0.4)
    plt.tight_layout()
    plt.savefig(fig_dir / "m_phi_convergence.png", dpi=180)
    plt.close()


def evaluate_on_full_grid(model, data):
    model.eval()

    with torch.no_grad():
        phi_pred = model(data["x_all"], data["t_all"])

    phi_true = data["phi_clean_all"]

    mse = torch.mean((phi_pred - phi_true) ** 2)
    rel_l2 = torch.linalg.norm(phi_pred - phi_true) / torch.linalg.norm(phi_true)

    n_t = len(data["t_grid"])
    n_x = len(data["x_grid"])

    phi_pred_grid = phi_pred.detach().cpu().numpy().reshape(n_t, n_x)

    return {
        "mse": float(mse.detach().cpu()),
        "rel_l2": float(rel_l2.detach().cpu()),
        "phi_pred_grid": phi_pred_grid,
    }


def plot_field_diagnostics(eval_results, data, fig_dir):
    x = data["x_grid"]
    t = data["t_grid"]
    phi_true = data["phi_grid"]
    phi_pred = eval_results["phi_pred_grid"]
    err = np.abs(phi_pred - phi_true)

    # final-time comparison
    plt.figure(figsize=(7, 4.5))
    plt.plot(x, phi_true[-1], label="solver data")
    plt.plot(x, phi_pred[-1], "--", label="PINN")
    plt.xlabel("x")
    plt.ylabel(r"$\phi(x,T)$")
    plt.title("Final-time profile")
    plt.legend()
    plt.grid(True, alpha=0.4)
    plt.tight_layout()
    plt.savefig(fig_dir / "phi_final_comparison.png", dpi=180)
    plt.close()

    # error heatmap
    plt.figure(figsize=(7, 4.5))
    plt.imshow(
        err,
        aspect="auto",
        origin="lower",
        extent=[x[0], x[-1], t[0], t[-1]],
    )
    plt.colorbar(label=r"$|\phi_\theta-\phi_{data}|$")
    plt.xlabel("x")
    plt.ylabel("t")
    plt.title("Absolute error heatmap")
    plt.tight_layout()
    plt.savefig(fig_dir / "phi_error_heatmap.png", dpi=180)
    plt.close()


def save_metrics(metrics, out_path):
    clean_metrics = {}
    for key, value in metrics.items():
        if isinstance(value, (float, int, str, bool)):
            clean_metrics[key] = value

    with open(out_path, "w") as f:
        json.dump(clean_metrics, f, indent=4)


