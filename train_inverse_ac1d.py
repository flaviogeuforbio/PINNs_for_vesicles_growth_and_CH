def evaluate_on_full_grid(
    model: nn.Module,
    data: Dict[str, Any],
) -> Dict[str, Any]:
    """
    Evaluate the trained model on the full clean solver grid.
    """
    model.eval()

    with torch.no_grad():
        phi_pred = model(data["x_all"], data["t_all"])

    phi_true = data["phi_clean_all"]

    mse = torch.mean((phi_pred - phi_true) ** 2)
    rel_l2 = torch.linalg.norm(phi_pred - phi_true) / torch.linalg.norm(phi_true)

    n_t = len(data["t_grid"])
    n_x = len(data["x_grid"])

    phi_pred_grid = phi_pred.detach().cpu().numpy().reshape(n_t, n_x)

    return {
        "mse": float(mse.detach().cpu()),
        "rel_l2": float(rel_l2.detach().cpu()),
        "phi_pred_grid": phi_pred_grid,
    }


def build_metrics(
    final_m_phi: float,
    data: Dict[str, Any],
    eval_results: Dict[str, Any],
    args: argparse.Namespace,
) -> Dict[str, Any]:
    """
    Build the final scalar metrics dictionary.
    """
    rel_m_phi_error = abs(final_m_phi - data["m_phi_true"]) / abs(data["m_phi_true"])

    return {
        "m_phi_true": float(data["m_phi_true"]),
        "m_phi_final": float(final_m_phi),
        "m_phi_relative_error": float(rel_m_phi_error),
        "full_grid_mse_phi": float(eval_results["mse"]),
        "full_grid_relative_l2_phi": float(eval_results["rel_l2"]),
        "data_fraction": float(args.data_fraction),
        "data_noise": float(args.data_noise),
        "n_observed_data_points": int(data["n_obs"]),
        "n_total_data_points": int(data["n_total"]),
        "seed": int(args.seed),
    }


