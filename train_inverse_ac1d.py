"""
train_inverse_ac1d.py
======================================================================
Minimal PINN benchmark for blind inverse inference of m_phi in 1D
source-free Allen-Cahn dynamics.

We train a neural network phi_theta(x,t) on numerical data generated by
generate_ac1d_data.py. The inverse problem is genuinely blind because:

    - no manufactured source term is used;
    - m_phi_true appears only in the saved dataset for final comparison;
    - the training loss uses only phi observations and the source-free PDE.

Model:
    phi_t + m_phi * mu(phi) = 0

with:
    mu(phi) = k * [ (1/eps)(phi^3 - phi) - eps * phi_xx ]

The unknown parameter is constrained positive via:
    m_phi = exp(log_m_phi)
"""

