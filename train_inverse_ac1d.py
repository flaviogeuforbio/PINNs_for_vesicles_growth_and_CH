# 5. Sampling
# ---------------------------------------------------------------------

def sample_data_batch(data, n_data: int, gen):
    """
    Sample observed points from the fixed observed dataset.
    Sampling is with replacement.
    """
    x_obs = data["x_obs"]
    t_obs = data["t_obs"]
    phi_obs = data["phi_obs"]

    n_obs = x_obs.shape[0]

    if n_data <= 0:
        return x_obs, t_obs, phi_obs

    idx = torch.randint(
        low=0,
        high=n_obs,
        size=(n_data,),
        device=x_obs.device,
        generator=gen,
    )

    return x_obs[idx], t_obs[idx], phi_obs[idx]


def sample_batches(data, args, device, gen):
    """
    Create one stochastic batch for data, PDE, IC and BC losses.
    """

    # supervised data
    x_data, t_data, phi_data = sample_data_batch(data, args.n_data, gen)

    # PDE collocation points in [0,1] x [0,T]
    x_pde = torch.rand((args.n_pde, 1), device=device, generator=gen)
    t_pde = torch.rand((args.n_pde, 1), device=device, generator=gen) * data["t_final"]

    # IC points: t = 0
    x_ic = torch.rand((args.n_ic, 1), device=device, generator=gen)
    t_ic = torch.zeros_like(x_ic)

    # BC points: x = 0 and x = 1
    n_half = max(1, args.n_bc // 2)

    t_bc_left = torch.rand((n_half, 1), device=device, generator=gen) * data["t_final"]
    t_bc_right = torch.rand((n_half, 1), device=device, generator=gen) * data["t_final"]

    x_bc_left = torch.zeros_like(t_bc_left)
    x_bc_right = torch.ones_like(t_bc_right)

    return {
        "x_data": x_data,
        "t_data": t_data,
        "phi_data": phi_data,

        "x_pde": x_pde,
        "t_pde": t_pde,

        "x_ic": x_ic,
        "t_ic": t_ic,

        "x_bc_left": x_bc_left,
        "t_bc_left": t_bc_left,
        "x_bc_right": x_bc_right,
        "t_bc_right": t_bc_right,
    }


# ---------------------------------------------------------------------
# 6. Loss evaluation
# ---------------------------------------------------------------------

def true_ic(x, data):
    """
    Exact initial condition used by generate_ac1d_data.py:
        phi(x,0) = ic_a0 + ic_b0*cos(pi*x)
    """
    if data["ic_a0"] is None or data["ic_b0"] is None:
        raise ValueError("ic_a0/ic_b0 not found in dataset.")

    return data["ic_a0"] + data["ic_b0"] * torch.cos(math.pi * x)


def evaluate_losses(model, log_m_phi, batch, data, args, use_pde: bool):
    """
    Compute all losses from one fixed batch.

    Important:
    x_pde, t_pde and boundary x tensors are cloned with requires_grad=True
    because PDE and BC losses need derivatives w.r.t. inputs.
    """

    m_phi = torch.exp(log_m_phi)

    # -------------------------
    # Data loss
    # -------------------------
    phi_pred_data = model(batch["x_data"], batch["t_data"])
    loss_data = torch.mean((phi_pred_data - batch["phi_data"]) ** 2)

    # -------------------------
    # IC loss
    # -------------------------
    phi_pred_ic = model(batch["x_ic"], batch["t_ic"])
    phi_true_ic = true_ic(batch["x_ic"], data)
    loss_ic = torch.mean((phi_pred_ic - phi_true_ic) ** 2)

    # -------------------------
    # BC loss: phi_x(0,t)=0 and phi_x(1,t)=0
    # -------------------------
    x_left = batch["x_bc_left"].detach().clone().requires_grad_(True)
    t_left = batch["t_bc_left"].detach().clone()

    x_right = batch["x_bc_right"].detach().clone().requires_grad_(True)
    t_right = batch["t_bc_right"].detach().clone()

    phi_left = model(x_left, t_left)
    phi_right = model(x_right, t_right)

    phi_x_left = grad(phi_left, x_left)
    phi_x_right = grad(phi_right, x_right)

    loss_bc = torch.mean(phi_x_left ** 2) + torch.mean(phi_x_right ** 2)

    # -------------------------
    # PDE loss
    # -------------------------
    if use_pde:
        x_pde = batch["x_pde"].detach().clone().requires_grad_(True)
        t_pde = batch["t_pde"].detach().clone().requires_grad_(True)

        phi_pde = model(x_pde, t_pde)
        phi_t = grad(phi_pde, t_pde)

        mu_pde = mu_from_phi(
            phi=phi_pde,
            x=x_pde,
            k=data["k"],
            eps=data["eps"],
        )

        residual = phi_t + m_phi * mu_pde
        loss_pde = torch.mean(residual ** 2)
    else:
        loss_pde = torch.zeros((), device=batch["x_data"].device)

    total = (
        args.data_weight * loss_data
        + args.ic_weight * loss_ic
        + args.bc_weight * loss_bc
        + args.pde_weight * loss_pde
    )

    losses = {
        "total": total,
        "data": loss_data,
        "ic": loss_ic,
        "bc": loss_bc,
        "pde": loss_pde,
        "m_phi": m_phi,
    }

    return total, losses


