def initialize_model_and_optimizer(
    args: argparse.Namespace,
    device: torch.device,
) -> Tuple[nn.Module, nn.Parameter, torch.optim.Optimizer]:
    """
    Initialize the PINN, log_m_phi and Adam optimizer.
    """
    model = SimpleAC1D(
        hidden_layers=args.hidden_layers,
        hidden_dim=args.hidden_dim,
    ).to(device)

    log_m_phi = nn.Parameter(
        torch.tensor(
            math.log(args.m_phi_init),
            dtype=torch.float32,
            device=device,
        )
    )

    optimizer = Adam(
        [
            {"params": model.parameters(), "lr": args.lr},
            {"params": [log_m_phi], "lr": args.m_phi_lr},
        ]
    )

    return model, log_m_phi, optimizer


def init_history() -> Dict[str, list]:
    """
    Initialize training history.
    """
    return {
        "total": [],
        "data": [],
        "ic": [],
        "bc": [],
        "pde": [],
        "m_phi": [],
        "phase": [],
    }


def append_history(
    history: Dict[str, list],
    losses: Dict[str, Tensor],
    phase: str,
) -> None:
    """
    Append one optimization step to the training history.
    """
    for key in ["total", "data", "ic", "bc", "pde", "m_phi"]:
        history[key].append(float(losses[key].detach().cpu()))

    history["phase"].append(phase)


def print_step(
    prefix: str,
    step: int,
    losses: Dict[str, Tensor],
    m_phi_true: float,
    include_pde: bool,
) -> None:
    """
    Print one training step in a compact format.
    """
    rel_err = abs(losses["m_phi"].item() - m_phi_true) / abs(m_phi_true)

    msg = (
        f"{prefix} {step:05d} | "
        f"Total: {losses['total'].item():.4e} | "
        f"Data: {losses['data'].item():.4e} | "
    )

    if include_pde:
        msg += f"PDE: {losses['pde'].item():.4e} | "

    msg += (
        f"IC: {losses['ic'].item():.4e} | "
        f"BC: {losses['bc'].item():.4e} | "
        f"m_phi: {losses['m_phi'].item():.6e} | "
        f"rel.err: {rel_err:.3e}"
    )

    print(msg)


def run_pretraining(
    model: nn.Module,
    log_m_phi: nn.Parameter,
    optimizer: torch.optim.Optimizer,
    data: Dict[str, Any],
    args: argparse.Namespace,
    device: torch.device,
    generator: torch.Generator,
    history: Dict[str, list],
) -> None:
    """
    Run the pretraining phase without PDE residuals.

    This phase fits observed data, initial condition and boundary condition
    before activating the source-free dynamics constraint.
    """
    if args.pretrain_epochs <= 0:
        return

    print("\n" + "=" * 40)
    print("PRETRAIN: data + IC + BC only")
    print("=" * 40)

    for epoch in range(1, args.pretrain_epochs + 1):
        model.train()

        batch = sample_batches(
            data=data,
            args=args,
            device=device,
            generator=generator,
        )

        optimizer.zero_grad()

        total, losses = evaluate_losses(
            model=model,
            log_m_phi=log_m_phi,
            batch=batch,
            data=data,
            args=args,
            use_pde=False,
        )

        total.backward()
        optimizer.step()

        append_history(history, losses, phase="pretrain")

        if epoch == 1 or epoch % args.print_every == 0:
            print_step(
                prefix="Pretrain",
                step=epoch,
                losses=losses,
                m_phi_true=data["m_phi_true"],
                include_pde=False,
            )


def run_adam_inverse_training(
    model: nn.Module,
    log_m_phi: nn.Parameter,
    optimizer: torch.optim.Optimizer,
    data: Dict[str, Any],
    args: argparse.Namespace,
    device: torch.device,
    generator: torch.Generator,
    history: Dict[str, list],
) -> None:
    """
    Run Adam inverse training with the source-free PDE residual active.
    """
    print("\n" + "=" * 40)
    print("ADAM INVERSE TRAINING")
    print("=" * 40)

    for epoch in range(1, args.epochs + 1):
        model.train()

        batch = sample_batches(
            data=data,
            args=args,
            device=device,
            generator=generator,
        )

        optimizer.zero_grad()

        total, losses = evaluate_losses(
            model=model,
            log_m_phi=log_m_phi,
            batch=batch,
            data=data,
            args=args,
            use_pde=True,
        )

        total.backward()
        optimizer.step()

        append_history(history, losses, phase="adam")

        if epoch == 1 or epoch % args.print_every == 0:
            print_step(
                prefix="Epoch",
                step=epoch,
                losses=losses,
                m_phi_true=data["m_phi_true"],
                include_pde=True,
            )


def run_lbfgs_refinement(
    model: nn.Module,
    log_m_phi: nn.Parameter,
    data: Dict[str, Any],
    args: argparse.Namespace,
    device: torch.device,
    generator: torch.Generator,
    history: Dict[str, list],
) -> None:
    """
    Optional L-BFGS refinement on one fixed stochastic batch.
    """
    if args.lbfgs_iter <= 0:
        return

    print("\n" + "=" * 40)
    print("L-BFGS REFINEMENT")
    print("=" * 40)

    fixed_batch = sample_batches(
        data=data,
        args=args,
        device=device,
        generator=generator,
    )

    lbfgs = torch.optim.LBFGS(
        list(model.parameters()) + [log_m_phi],
        lr=1.0,
        max_iter=args.lbfgs_iter,
        max_eval=args.lbfgs_iter * 2,
        history_size=50,
        tolerance_grad=1e-10,
        tolerance_change=1e-12,
        line_search_fn="strong_wolfe",
    )

    def closure() -> Tensor:
        lbfgs.zero_grad()

        total, losses = evaluate_losses(
            model=model,
            log_m_phi=log_m_phi,
            batch=fixed_batch,
            data=data,
            args=args,
            use_pde=True,
        )

        total.backward()
        append_history(history, losses, phase="lbfgs")

        return total

    lbfgs.step(closure)

    final_m_phi = float(torch.exp(log_m_phi).detach().cpu())
    print(f"L-BFGS completed | m_phi = {final_m_phi:.8e}")


