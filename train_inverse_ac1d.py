    if args.pretrain_epochs < 0:
        raise ValueError("pretrain_epochs must be non-negative.")
    if args.lr <= 0.0:
        raise ValueError("lr must be positive.")
    if args.m_phi_lr <= 0.0:
        raise ValueError("m_phi_lr must be positive.")
    if args.lbfgs_iter < 0:
        raise ValueError("lbfgs_iter must be non-negative.")
    if args.print_every <= 0:
        raise ValueError("print_every must be positive.")
    if args.m_phi_init <= 0.0:
        raise ValueError("m_phi_init must be positive because log(m_phi_init) is used.")
