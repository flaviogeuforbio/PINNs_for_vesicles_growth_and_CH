def grad(u: Tensor, z: Tensor) -> Tensor:
    """
    Compute du/dz using PyTorch autograd.
    """
    return torch.autograd.grad(
        u,
        z,
        grad_outputs=torch.ones_like(u),
        create_graph=True,
        retain_graph=True,
    )[0]


def mu_from_phi(
    phi: Tensor,
    x: Tensor,
    k: float,
    eps: float,
) -> Tensor:
    """
    Compute the Allen-Cahn chemical potential from phi_theta:

        mu = k * [ (1/eps)(phi^3 - phi) - eps * phi_xx ].
    """
    phi_x = grad(phi, x)
    phi_xx = grad(phi_x, x)

    mu = k * ((phi**3 - phi) / eps - eps * phi_xx)

    return mu


