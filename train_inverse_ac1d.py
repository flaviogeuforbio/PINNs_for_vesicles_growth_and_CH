def load_ac1d_data(args: argparse.Namespace, device: torch.device) -> Dict[str, Any]:
    """
    Load an AC1D dataset generated by generate_ac1d_data.py.

    Expected NPZ keys
    -----------------
    x, t, phi, m_phi_true, k, eps, ic_a0, ic_b0

    Notes
    -----
    phi is expected with shape (n_t, n_x). The supervised dataset is built by
    flattening the full space-time solver grid.

    Data degradation is applied once at loading time:
    - data_fraction selects a fixed random observed subset;
    - data_noise adds fixed relative Gaussian noise to the full phi field before
      the observed subset is extracted.
    """
    data_npz = np.load(args.data_path)

    x_grid = data_npz["x"].astype(np.float32)
    t_grid = data_npz["t"].astype(np.float32)
    phi_grid = data_npz["phi"].astype(np.float32)

    m_phi_true = float(data_npz["m_phi_true"])
    k = float(data_npz["k"])
    eps = float(data_npz["eps"])

    ic_a0 = float(data_npz["ic_a0"]) if "ic_a0" in data_npz else None
    ic_b0 = float(data_npz["ic_b0"]) if "ic_b0" in data_npz else None

    expected_shape = (len(t_grid), len(x_grid))

    if phi_grid.shape != expected_shape:
        raise ValueError(f"Expected phi shape {expected_shape}, got {phi_grid.shape}.")

    t_final = float(t_grid[-1])

    x_mesh = np.tile(x_grid[None, :], (len(t_grid), 1))
    t_mesh = np.tile(t_grid[:, None], (1, len(x_grid)))

    x_all = torch.tensor(
        x_mesh.reshape(-1, 1),
        dtype=torch.float32,
        device=device,
    )
    t_all = torch.tensor(
        t_mesh.reshape(-1, 1),
        dtype=torch.float32,
        device=device,
    )
    phi_clean_all = torch.tensor(
        phi_grid.reshape(-1, 1),
        dtype=torch.float32,
        device=device,
    )

    phi_obs_all = phi_clean_all.clone()

    if args.data_noise > 0.0:
        generator = torch.Generator(device=device)
        generator.manual_seed(args.seed + 1000)

        scale = torch.std(phi_clean_all)

        noise = torch.randn(
            phi_clean_all.shape,
            generator=generator,
            device=device,
            dtype=phi_clean_all.dtype,
        )

        phi_obs_all = phi_clean_all + args.data_noise * scale * noise

    n_total = x_all.shape[0]
    n_obs = max(1, int(round(args.data_fraction * n_total)))

    rng = np.random.default_rng(args.seed)
    obs_idx_np = rng.choice(n_total, size=n_obs, replace=False)
    obs_idx = torch.tensor(obs_idx_np, dtype=torch.long, device=device)

    data = {
        # Observed tensors for training.
        "x_obs": x_all[obs_idx],
        "t_obs": t_all[obs_idx],
        "phi_obs": phi_obs_all[obs_idx],
        # Full clean tensors for final evaluation.
        "x_all": x_all,
        "t_all": t_all,
        "phi_clean_all": phi_clean_all,
        # NumPy arrays for plotting.
        "x_grid": x_grid,
        "t_grid": t_grid,
        "phi_grid": phi_grid,
        # Physical and dataset metadata.
        "m_phi_true": m_phi_true,
        "k": k,
        "eps": eps,
        "ic_a0": ic_a0,
        "ic_b0": ic_b0,
        "t_final": t_final,
        "n_total": int(n_total),
        "n_obs": int(n_obs),
    }

    return data


