def main():
    args = parse_args()

    torch.manual_seed(args.seed)
    np.random.seed(args.seed)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    run_dir = Path("artifacts") / args.run_name
    fig_dir = run_dir / "figures"
    weights_dir = run_dir / "weights"

    fig_dir.mkdir(parents=True, exist_ok=True)
    weights_dir.mkdir(parents=True, exist_ok=True)

    print("=" * 80)
    print("AC1D BLIND INVERSE PINN")
    print("=" * 80)
    print(f"Device      : {device}")
    print(f"Data path   : {args.data_path}")
    print(f"Run dir     : {run_dir}")
    print(f"m_phi_init  : {args.m_phi_init}")
    print("=" * 80)

    data = load_ac1d_data(args, device)

    print("Loaded data:")
    print(f"  m_phi_true        = {data['m_phi_true']:.6f}")
    print(f"  k                 = {data['k']:.6f}")
    print(f"  eps               = {data['eps']:.6f}")
    print(f"  T_final           = {data['t_final']:.6f}")
    print(f"  total data points = {data['n_total']}")
    print(f"  observed points   = {data['n_obs']}")
    print(f"  data_fraction     = {args.data_fraction}")
    print(f"  data_noise        = {args.data_noise}")
    print("=" * 80)

    save_config(args, data, run_dir)

    model = SimpleAC1D(
        hidden_layers=args.hidden_layers,
        hidden_dim=args.hidden_dim
    ).to(device)

    log_m_phi = nn.Parameter(
        torch.tensor(math.log(args.m_phi_init), dtype=torch.float32, device=device)
    )

    optimizer = Adam(
        [
            {"params": model.parameters(), "lr": args.lr},
            {"params": [log_m_phi], "lr": args.m_phi_lr},
        ]
    )

    gen = torch.Generator(device=device)
    gen.manual_seed(args.seed + 2000)

    history = {
        "total": [],
        "data": [],
        "ic": [],
        "bc": [],
        "pde": [],
        "m_phi": [],
    }

    # ------------------------------------------------------------
    # Phase 1: pretraining without PDE
    # ------------------------------------------------------------
    if args.pretrain_epochs > 0:
        print("\n" + "=" * 40)
        print("PRETRAIN: data + IC + BC only")
        print("=" * 40)

        for epoch in range(1, args.pretrain_epochs + 1):
            model.train()
            batch = sample_batches(data, args, device, gen)

            optimizer.zero_grad()
            total, losses = evaluate_losses(
                model=model,
                log_m_phi=log_m_phi,
                batch=batch,
                data=data,
                args=args,
                use_pde=False,
            )
            total.backward()
            optimizer.step()

            append_history(history, losses)

            if epoch == 1 or epoch % args.print_every == 0:
                print(
                    f"Pretrain {epoch:05d} | "
                    f"Total: {losses['total'].item():.4e} | "
                    f"Data: {losses['data'].item():.4e} | "
                    f"IC: {losses['ic'].item():.4e} | "
                    f"BC: {losses['bc'].item():.4e} | "
                    f"m_phi: {losses['m_phi'].item():.6e}"
                )

    # ------------------------------------------------------------
    # Phase 2: inverse training with PDE
    # ------------------------------------------------------------
    print("\n" + "=" * 40)
    print("ADAM INVERSE TRAINING")
    print("=" * 40)

    for epoch in range(1, args.epochs + 1):
        model.train()
        batch = sample_batches(data, args, device, gen)

        optimizer.zero_grad()
        total, losses = evaluate_losses(
            model=model,
            log_m_phi=log_m_phi,
            batch=batch,
            data=data,
            args=args,
            use_pde=True,
        )
        total.backward()
        optimizer.step()

        append_history(history, losses)

        if epoch == 1 or epoch % args.print_every == 0:
            rel_err = abs(losses["m_phi"].item() - data["m_phi_true"]) / abs(data["m_phi_true"])
            print(
                f"Epoch {epoch:05d} | "
                f"Total: {losses['total'].item():.4e} | "
                f"Data: {losses['data'].item():.4e} | "
                f"PDE: {losses['pde'].item():.4e} | "
                f"IC: {losses['ic'].item():.4e} | "
                f"BC: {losses['bc'].item():.4e} | "
                f"m_phi: {losses['m_phi'].item():.6e} | "
                f"rel.err: {rel_err:.3e}"
            )

    # ------------------------------------------------------------
    # Optional L-BFGS refinement on one fixed batch
    # ------------------------------------------------------------
    if args.lbfgs_iter > 0:
        print("\n" + "=" * 40)
        print("L-BFGS REFINEMENT")
        print("=" * 40)

        fixed_batch = sample_batches(data, args, device, gen)

        lbfgs = torch.optim.LBFGS(
            list(model.parameters()) + [log_m_phi],
            lr=1.0,
            max_iter=args.lbfgs_iter,
            max_eval=args.lbfgs_iter * 2,
            history_size=50,
            tolerance_grad=1e-10,
            tolerance_change=1e-12,
            line_search_fn="strong_wolfe",
        )

        def closure():
            lbfgs.zero_grad()

            total, losses = evaluate_losses(
                model=model,
                log_m_phi=log_m_phi,
                batch=fixed_batch,
                data=data,
                args=args,
                use_pde=True,
            )

            total.backward()
            append_history(history, losses)
            return total

        lbfgs.step(closure)

        with torch.no_grad():
            final_m = torch.exp(log_m_phi).item()
        print(f"L-BFGS completed | m_phi = {final_m:.8e}")

    # ------------------------------------------------------------
    # Save final artifacts
    # ------------------------------------------------------------
    torch.save(model.state_dict(), weights_dir / "model.pt")

    with torch.no_grad():
        final_m_phi = float(torch.exp(log_m_phi).detach().cpu())

    eval_results = evaluate_on_full_grid(model, data)

    rel_m_phi_error = abs(final_m_phi - data["m_phi_true"]) / abs(data["m_phi_true"])

    metrics = {
        "m_phi_true": data["m_phi_true"],
        "m_phi_final": final_m_phi,
        "m_phi_relative_error": rel_m_phi_error,
        "full_grid_mse_phi": eval_results["mse"],
        "full_grid_relative_l2_phi": eval_results["rel_l2"],
        "data_fraction": args.data_fraction,
        "data_noise": args.data_noise,
        "n_observed_data_points": data["n_obs"],
    }

    save_metrics(metrics, run_dir / "metrics.json")

    plot_losses(history, fig_dir)
    plot_m_phi(history, data, fig_dir)
    plot_field_diagnostics(eval_results, data, fig_dir)

    print("\n" + "=" * 80)
    print("FINAL RESULTS")
    print("=" * 80)
    print(f"m_phi_true             : {data['m_phi_true']:.8e}")
    print(f"m_phi_final            : {final_m_phi:.8e}")
    print(f"m_phi_relative_error   : {rel_m_phi_error:.8e}")
    print(f"full_grid_mse_phi      : {eval_results['mse']:.8e}")
    print(f"full_grid_rel_l2_phi   : {eval_results['rel_l2']:.8e}")
    print(f"Saved run to           : {run_dir}")
    print("=" * 80)


if __name__ == "__main__":
    main()