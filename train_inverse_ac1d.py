def sample_data_batch(
    data: Dict[str, Any],
    n_data: int,
    generator: torch.Generator,
) -> Tuple[Tensor, Tensor, Tensor]:
    """
    Sample observed data points from the fixed observed subset.

    Sampling is with replacement. If n_data <= 0, all observed points are used.
    """
    x_obs = data["x_obs"]
    t_obs = data["t_obs"]
    phi_obs = data["phi_obs"]

    n_obs = x_obs.shape[0]

    if n_data <= 0:
        return x_obs, t_obs, phi_obs

    idx = torch.randint(
        low=0,
        high=n_obs,
        size=(n_data,),
        device=x_obs.device,
        generator=generator,
    )

    return x_obs[idx], t_obs[idx], phi_obs[idx]


def sample_batches(
    data: Dict[str, Any],
    args: argparse.Namespace,
    device: torch.device,
    generator: torch.Generator,
) -> Dict[str, Tensor]:
    """
    Sample one stochastic batch for data, PDE, IC and BC losses.
    """
    x_data, t_data, phi_data = sample_data_batch(
        data=data,
        n_data=args.n_data,
        generator=generator,
    )

    x_pde = torch.rand((args.n_pde, 1), device=device, generator=generator)
    t_pde = torch.rand((args.n_pde, 1), device=device, generator=generator) * data["t_final"]

    x_ic = torch.rand((args.n_ic, 1), device=device, generator=generator)
    t_ic = torch.zeros_like(x_ic)

    n_half = max(1, args.n_bc // 2)

    t_bc_left = torch.rand((n_half, 1), device=device, generator=generator) * data["t_final"]
    t_bc_right = torch.rand((n_half, 1), device=device, generator=generator) * data["t_final"]

    x_bc_left = torch.zeros_like(t_bc_left)
    x_bc_right = torch.ones_like(t_bc_right)

    return {
        "x_data": x_data,
        "t_data": t_data,
        "phi_data": phi_data,
        "x_pde": x_pde,
        "t_pde": t_pde,
        "x_ic": x_ic,
        "t_ic": t_ic,
        "x_bc_left": x_bc_left,
        "t_bc_left": t_bc_left,
        "x_bc_right": x_bc_right,
        "t_bc_right": t_bc_right,
    }


