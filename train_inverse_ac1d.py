def save_config(
    args: argparse.Namespace,
    data: Dict[str, Any],
    run_dir: Path,
) -> None:
    """
    Save the full run configuration to JSON.
    """
    config = vars(args).copy()

    config.update(
        {
            "m_phi_true": data["m_phi_true"],
            "k": data["k"],
            "eps": data["eps"],
            "t_final": data["t_final"],
            "n_total_data_points": data["n_total"],
            "n_observed_data_points": data["n_obs"],
        }
    )

    with open(run_dir / "run_config.json", "w") as f:
        json.dump(config, f, indent=4)


def save_history(history: Dict[str, list], out_path: Path) -> None:
    """
    Save optimization history to JSON.
    """
    with open(out_path, "w") as f:
        json.dump(history, f, indent=4)


def save_metrics(metrics: Dict[str, Any], out_path: Path) -> None:
    """
    Save scalar final metrics to JSON.
    """
    clean_metrics = {}

    for key, value in metrics.items():
        if isinstance(value, (float, int, str, bool)):
            clean_metrics[key] = value

    with open(out_path, "w") as f:
        json.dump(clean_metrics, f, indent=4)


def plot_losses(history: Dict[str, list], fig_dir: Path) -> None:
    """
    Plot the training loss history.
    """
    fig_dir.mkdir(parents=True, exist_ok=True)

    plt.figure(figsize=(8, 5))

    for key in ["total", "data", "pde", "ic", "bc"]:
        values = np.array(history[key], dtype=np.float64)
        values = np.maximum(values, 1e-16)
        plt.semilogy(values, label=key)

    plt.xlabel("Optimization step")
    plt.ylabel("Loss")
    plt.title("AC1D blind inverse training losses")
    plt.legend()
    plt.grid(True, which="both", linestyle="--", alpha=0.4)
    plt.tight_layout()
    plt.savefig(fig_dir / "losses.png", dpi=180)
    plt.close()


def plot_m_phi(
    history: Dict[str, list],
    data: Dict[str, Any],
    fig_dir: Path,
) -> None:
    """
    Plot the learned mobility trajectory.
    """
    plt.figure(figsize=(8, 5))

    m_values = np.array(history["m_phi"], dtype=np.float64)

    plt.plot(m_values, label=r"learned $m_\phi$")
    plt.axhline(
        data["m_phi_true"],
        linestyle="--",
        color="black",
        label=r"true $m_\phi$",
    )

    plt.xlabel("Optimization step")
    plt.ylabel(r"$m_\phi$")
    plt.title("Blind inverse inference of mobility")
    plt.legend()
    plt.grid(True, alpha=0.4)
    plt.tight_layout()
    plt.savefig(fig_dir / "m_phi_convergence.png", dpi=180)
    plt.close()


def plot_field_diagnostics(
    eval_results: Dict[str, Any],
    data: Dict[str, Any],
    fig_dir: Path,
) -> None:
    """
    Plot final-time comparison and full space-time absolute error.
    """
    x_grid = data["x_grid"]
    t_grid = data["t_grid"]

    phi_true = data["phi_grid"]
    phi_pred = eval_results["phi_pred_grid"]
    error = np.abs(phi_pred - phi_true)

    plt.figure(figsize=(7, 4.5))
    plt.plot(x_grid, phi_true[-1], label="solver data")
    plt.plot(x_grid, phi_pred[-1], "--", label="PINN")
    plt.xlabel("x")
    plt.ylabel(r"$\phi(x,T)$")
    plt.title("Final-time profile")
    plt.legend()
    plt.grid(True, alpha=0.4)
    plt.tight_layout()
    plt.savefig(fig_dir / "phi_final_comparison.png", dpi=180)
    plt.close()

    plt.figure(figsize=(7, 4.5))
    plt.imshow(
        error,
        aspect="auto",
        origin="lower",
        extent=[x_grid[0], x_grid[-1], t_grid[0], t_grid[-1]],
    )
    plt.colorbar(label=r"$|\phi_\theta-\phi_{\mathrm{data}}|$")
    plt.xlabel("x")
    plt.ylabel("t")
    plt.title("Absolute error heatmap")
    plt.tight_layout()
    plt.savefig(fig_dir / "phi_error_heatmap.png", dpi=180)
    plt.close()


